#!/usr/bin/env python3
"""Generate curriculum/README.md, the learner-facing map of OSVR, from curriculum/skill-tree.yaml.

Usage: python3 scripts/build_index.py          write curriculum/README.md
       python3 scripts/build_index.py --check  exit 1 if curriculum/README.md is out of date

The node order in skill-tree.yaml is the recommended study order. Do not edit the generated
file by hand: change skill-tree.yaml or this script, then re-run.
"""
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("needs PyYAML: pip install pyyaml (or your distro's python3-yaml)")

ROOT = Path(__file__).resolve().parent.parent
TREE = ROOT / "curriculum" / "skill-tree.yaml"
OUT = ROOT / "curriculum" / "README.md"

STATUS = {
    "ready": "ready",
    "drafting": "draft, not yet audited",
    "planned": "not written yet",
    "deprecated": "deprecated",
}

HEADER = """# OSVR curriculum: start here

<!-- Generated by scripts/build_index.py from curriculum/skill-tree.yaml. Do not edit by hand. -->

This page is the map. It lists every module in the order you should take them, says which ones exist yet, and links to each one.

## Before your first session

1. **Install a container engine.** Use rootless **podman**; it is the only engine the labs are verified on. Docker may work but is untested (see FND-01).
2. **Clone this repository** and work from its root. Your own progress lives in `learner/`, which is private to you.
3. **Open the first module**, `FND-01`, and follow its README from the top. FND-01 needs no programming.
4. **Can you already program?** At the end of FND-01 you take a 90-minute diagnostic. Pass it and go straight to FND-02. Otherwise take `FND-00` (programming on-ramp) first.

If you use Claude Code in this repo, `/coach next` starts a guided session on the next module, and `/review` runs your due flashcards. Everything also works without it.

## How to work through a module

Each module is a folder. Use its files in this order:

| Step | File | What you do |
|---|---|---|
| 1 | `README.md` | Prerequisite check, then (if you are new to the technique) the worked example, then the **closed-book struggle challenge**, then theory, walkthrough and consolidation. Do not skip ahead to the walkthrough. |
| 2 | `drills.md` | Short, repeatable drills on the module's hardest sub-skill. |
| 3 | `project.md` | The main task, on a real CVE or real codebase, plus variations. |
| 4 | `rubric.md` | How your project is graded. Read it before you start the project, check against it when you finish. |
| 5 | `cards.yaml` | Flashcards. Import with `python3 scripts/srs.py import <MODULE_ID>` and review them daily. |
| - | `lab/` | The module's container lab. Its README says how to build, run and check. |
| - | `resources.yaml` | Verified outside reading. Only the `core` entries are expected; the rest are optional. |

A module is done when you meet the pass criteria in `rubric.md`, not when you have read it.

## What the status column means

- **ready**: written, lab verified, passed audit. Use it.
- **draft, not yet audited**: written but may contain errors. Usable with care; report problems.
- **not written yet**: planned only; the link appears once the module exists.
"""

FOOTER = """
## Where everything else lives

- `curriculum/tracks/<TRACK>/MAP.md`: why each track exists and what it leads to.
- `curriculum/skill-tree.yaml`: the source of truth for order, prerequisites and hours.
- `docs/ULTRALEARNING.md`: the learning method behind the module structure.
- `research/`, `decisions/`, `maintenance/`, `templates/`, `prompts/`: how the curriculum is built and maintained. Learners can ignore these.
"""


def module_dir(node):
    d = ROOT / "curriculum" / "tracks" / node["track"] / "modules" / node["id"]
    return d if (d / "README.md").is_file() else None


def render(tree):
    tracks = tree["tracks"]
    nodes = tree["nodes"]
    out = [HEADER]

    core_ids = [t for t, v in tracks.items() if v.get("core")]
    elect_ids = [t for t, v in tracks.items() if not v.get("core")]
    counts = {s: 0 for s in STATUS}
    for n in nodes:
        counts[n.get("status", "planned")] = counts.get(n.get("status", "planned"), 0) + 1

    core_nodes = [n for n in nodes if n["track"] in core_ids]
    core_hours = sum(n["hours"] for n in core_nodes if not n.get("conditional"))
    cond_hours = sum(n["hours"] for n in core_nodes if n.get("conditional"))
    out.append("## Progress of the curriculum itself\n")
    out.append(
        f"{counts.get('ready', 0)} ready, {counts.get('drafting', 0)} in draft, "
        f"{counts.get('planned', 0)} not written yet, out of {len(nodes)} modules.\n\n"
        f"Core path: {core_hours} hours (about {round(core_hours / 10 / 4.33)} months at 10 h/week)"
        + (f", plus {cond_hours} h if you need the programming on-ramp." if cond_hours else ".")
        + "\n"
    )

    out.append("## The core path, in order\n")
    out.append("Take these top to bottom. Hours include drills and the project. "
               "PRO modules are deliberately mixed in.\n")
    out.append("| # | Module | Track | Hours | Cumulative | Status |")
    out.append("|---|---|---|---|---|---|")
    cum = 0
    i = 0
    for n in core_nodes:
        cond = n.get("conditional")
        if not cond:
            cum += n["hours"]
            i += 1
            num, cumtxt = str(i), str(cum)
        else:
            num, cumtxt = "(if needed)", "-"
        d = module_dir(n)
        title = f"`{n['id']}`: {n['title']}"
        cell = f"[{title}]({d.relative_to(OUT.parent).as_posix()}/README.md)" if d else title
        if cond:
            cell += f"<br>*Only {cond.removeprefix('only ')}*"
        out.append(f"| {num} | {cell} | {n['track']} | {n['hours']} | {cumtxt} | "
                   f"{STATUS.get(n.get('status', 'planned'), n.get('status'))} |")
    out.append("")

    out.append("## Tracks\n")
    out.append("| Track | Title | Kind | Modules | Hours | Map |")
    out.append("|---|---|---|---|---|---|")
    for t, v in tracks.items():
        tn = [n for n in nodes if n["track"] == t]
        m = ROOT / "curriculum" / "tracks" / t / "MAP.md"
        link = f"[MAP.md](tracks/{t}/MAP.md)" if m.is_file() else "not written yet"
        kind = "core" if v.get("core") else "elective"
        out.append(f"| {t} | {v['title']} | {kind} | {len(tn)} | {sum(x['hours'] for x in tn)} | {link} |")
    out.append("")

    if elect_ids:
        out.append("## Electives (after the core)\n")
        out.append("Specialisations. These are placeholders: they get detailed design after the core is built.\n")
        for t in elect_ids:
            tn = [n for n in nodes if n["track"] == t]
            out.append(f"- **{t}, {tracks[t]['title']}**: " +
                       ", ".join(f"`{n['id']}`" for n in tn))
        out.append("")

    out.append(FOOTER)
    return "\n".join(out)


def main():
    tree = yaml.safe_load(TREE.read_text(encoding="utf-8"))
    text = render(tree)
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 scripts/build_index.py")
            sys.exit(1)
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
